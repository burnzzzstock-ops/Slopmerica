// Bake one useful Civic Foundry trim into the existing MB/atlas batch. The
// catalog's textures and loaders are not shipped with this extracted module.
// --check verifies that the committed helper still matches its source asset.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';

const input = 'public/asset-library/models/facade-classical-cornice.lod1.gltf';
const output = 'src/buildings/civicCornice.ts';
const json = readFileSync(input, 'utf8'), doc = JSON.parse(json);
const bin = readFileSync(join(dirname(input), doc.buffers[0].uri));
if (doc.nodes.some(n => n.matrix || n.translation || n.rotation || n.scale)) throw Error('Bake node transforms before extracting this kit');
const colors = { limestone: 0xd8d4cc, 'metal-dark': 0x4b5157 };
const parts = [];
for (const mesh of doc.meshes) for (const p of mesh.primitives) {
  const material = doc.materials[p.material].name;
  if (!(material in colors)) continue;
  const a = doc.accessors[p.attributes.POSITION], v = doc.bufferViews[a.bufferView];
  if (p.indices !== undefined || a.componentType !== 5126 || a.type !== 'VEC3' || v.byteStride || p.mode !== 4) throw Error('Expected unindexed float triangles');
  const offset = (v.byteOffset || 0) + (a.byteOffset || 0);
  const positions = Array.from({ length: a.count * 3 }, (_, i) => bin.readFloatLE(offset + i * 4));
  if (!positions.every(Number.isFinite)) throw Error('Invalid source vertices');
  parts.push({ color: colors[material], positions });
}
const min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
for (const p of parts) p.positions.forEach((v, i) => { const k = i % 3; min[k] = Math.min(min[k], v); max[k] = Math.max(max[k], v); });
for (const p of parts) p.positions = p.positions.map((v, i) => {
  const k = i % 3;
  return +((v - min[k]) / (max[k] - min[k]) - (k === 0 ? 0.5 : 0)).toFixed(6);
});
const triangles = parts.reduce((n, p) => n + p.positions.length / 9, 0);
if (triangles !== 36) throw Error('Re-review the geometry budget after a source change');
const hash = createHash('sha256').update(json).update(bin).digest('hex');
const code = `// Generated by node scripts/building-kit.mjs from Civic Foundry's LOD1 cornice.
// Stone and metal trim only; ${triangles} triangles, no runtime catalog or texture load.
// Source SHA-256: ${hash}
import { S, type MB, type V3 } from './mesh';

const PARTS = ${JSON.stringify(parts)};

export function civicCornice(mb: MB, x0: number, x1: number, y: number, z: number) {
  mb.push().translate((x0 + x1) / 2, y, z).scale(x1 - x0, 0.6, 0.35);
  for (const part of PARTS) {
    const mat = S('plain', part.color, { ao: true }), p = part.positions;
    for (let i = 0; i < p.length; i += 9) {
      const points: V3[] = [[p[i], p[i+1], p[i+2]], [p[i+3], p[i+4], p[i+5]], [p[i+6], p[i+7], p[i+8]]];
      mb.poly(points, mat);
    }
  }
  mb.pop();
}
`;
if (Buffer.byteLength(code) > 1.5 * 1024 * 1024) throw Error('Extracted module exceeds the distribution growth allowance');
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== code) throw Error('Run node scripts/building-kit.mjs to update the extracted helper');
} else writeFileSync(output, code);
console.log(JSON.stringify({ source: input, output, triangles, sourceHash: hash, bytes: Buffer.byteLength(code) }));
