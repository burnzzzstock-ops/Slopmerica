import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createServer } from 'vite';

const server = await createServer({ cacheDir:'shots/tmp/vite/road-surface-'+process.pid, server:{ middlewareMode:true, watch:null, hmr:false, ws:false }, appType:'custom', logLevel:'error' });
try {
  const { RoadSurfaceState, roadDepression } = await server.ssrLoadModule('/src/roads/roadSurface.ts');
  const { lineCubic, sampleCubic } = await server.ssrLoadModule('/src/core/math.ts');
  const { SURF_LIFT } = await server.ssrLoadModule('/src/roads/roadSection.ts');
  const { Emitter } = await server.ssrLoadModule('/src/core/events.ts');
  const samples = sampleCubic(lineCubic({x:-50,z:0},{x:50,z:0}));
  const makeSegment = (id, height) => ({ id, a:id*2, b:id*2+1, type:'twoLane', samp:samples, length:100, hs:samples.pts.map(point=>height(point.x)),minX:-50,minZ:0,maxX:50,maxZ:0 });
  const flat = makeSegment(1, () => 10), bridge = makeSegment(2, () => 30);
  const dip = makeSegment(3, x => 10 + x*x*.003);
  const crest = makeSegment(4, x => 10 - x*x*.003);
  const slope = makeSegment(5, x => 10 + x*.08);
  assert.equal(roadDepression(flat,50),0);
  assert.equal(roadDepression(crest,50),0);
  assert.ok(roadDepression(slope,50)<1e-12);
  assert.equal(roadDepression(dip,50),1);
  assert.equal(roadDepression(dip,5),0);
  const net = { segs:new Map([[1,flat],[2,bridge]]), nodes:new Map(), segsNear:()=>[...net.segs.values()], events:new Emitter() };
  const state = new RoadSurfaceState(net);
  let fresh = false;
  state.setProvider(id => fresh ? 1 : id===1 ? .2 : .8);
  state.update();state.resetGeometry();
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position',new THREE.Float32BufferAttribute([0,10+SURF_LIFT,0,0,30+SURF_LIFT,0],3));
  const original = [...geometry.attributes.position.array];
  state.attach(geometry);
  const attribute = geometry.getAttribute('aRoadState');
  assert.ok(Math.abs(attribute.getX(0)-.2)<1e-6,'ground road condition');
  assert.ok(Math.abs(attribute.getX(1)-.8)<1e-6,'bridge condition must remain separate');
  const version = attribute.version;
  state.update();assert.equal(attribute.version,version,'unchanged conditions must skip upload');
  fresh=true;state.update();
  assert.equal(attribute.getX(0),1);assert.equal(attribute.getX(1),1);
  assert.ok(attribute.version>version,'repair refreshes the visual condition');
  assert.deepEqual([...geometry.attributes.position.array],original);
  const cached = state.samples.size;
  state.resetGeometry();state.attach(geometry);
  assert.equal(state.samples.size,cached,'unchanged geometry reuses spatial samples');
  net.events.emit('nodeChanged',{x:1000,z:1000});
  assert.equal(state.samples.size,cached,'distant topology keeps this neighbourhood cached');
  flat.minX=1000;flat.maxX=1100;
  net.events.emit('segChanged',flat);
  assert.equal(state.samples.size,0,'a moved segment invalidates its old bounds as well');
  flat.minX=-50;flat.maxX=50;
  state.resetGeometry();state.attach(geometry);
  net.segs.delete(2);state.update();
  assert.equal(state.conditions.has(2),false,'removed roads must leave the condition cache');
  net.events.emit('segRemoved',bridge);
  assert.equal(state.samples.size,0,'topology events invalidate affected sample neighbourhoods');
  state.resetGeometry();state.attach(geometry);
  assert.equal(geometry.getAttribute('aRoadState').getX(1),1,'removed bridge must not inherit the road below');
  fresh=false;
  net.nodes.set(flat.b,{id:flat.b,x:50,z:0,y:6,segs:[flat.id]});
  net.events.emit('nodeChanged',net.nodes.get(flat.b));
  state.update();state.resetGeometry();
  const cap=new THREE.BufferGeometry();
  cap.setAttribute('position',new THREE.Float32BufferAttribute([40,6+SURF_LIFT,0,40,30+SURF_LIFT,0],3));
  state.attach(cap);
  assert.ok(Math.abs(cap.getAttribute('aRoadState').getX(0)-.2)<1e-6,'a steep end cap inherits its endpoint road condition');
  assert.equal(cap.getAttribute('aRoadState').getX(1),1,'endpoint sampling still rejects a different elevation');
  console.log('PASS genuine dips, flat/slope/crest exclusion, grade-separated ages, repair updates and unchanged positions');
} finally { await server.close(); }
